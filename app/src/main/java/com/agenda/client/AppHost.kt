package com.agenda.client

/**
 * Договор между экранами-фрагментами и MainActivity.
 *
 * Зачем: «движок» (скрытый WebView, вход на портал, запись истории) живёт в Activity и не должен
 * пересоздаваться при переключении разделов. Фрагменты про WebView ничего не знают: они только
 * читают готовое состояние и просят о действиях через этот интерфейс.
 */
interface AppHost {
    /** Последний показанный список оценок (с датами). */
    val grades: List<SubjectGrades>

    /** Строка статуса: «Обновлено в 14:05 · новых оценок нет» и т.п. */
    val status: String

    /** Логин текущего аккаунта (пароль наружу не отдаём никогда). */
    val username: String

    /** Кем вошли: родитель или ученик. */
    val accountType: AccountType

    /** Экран подписывается на изменения; при уходе обязан отписаться (передать null). */
    fun setStateListener(listener: (() -> Unit)?)

    /** Кнопка «Обновить»: Activity сама проверит, не рано ли ходить на портал. */
    fun requestRefresh()

    /** Спросить подтверждение и стереть все данные аккаунта с телефона. */
    fun confirmLogout()
}
